# Ejercicio 1: Cálculo de la velocidad final

#Determina la velocidad final de un auto si su velocidad inicial es 0 km/h
#y su aceleración es 0.8 m/s2; y el tiempo transcurrido es de 30 segundos.

vi = 0          # m/s
a = 0.8         # m/s²
t = 30          # s

vf = vi + a * t

print("Velocidad final:", vf, "m/s")